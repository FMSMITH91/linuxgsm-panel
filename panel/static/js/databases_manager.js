// The Databases manager on the Databases page (templates/databases_overview.html; routes
// databases.py, databases_data.py, databases_files.py). Loaded only for a viewer with Manage
// databases. Nothing is asked of a host until a database's dialog is opened, and each tab loads
// when it is first shown. Every value read from a database is put on the page with textContent
// (never as markup); a password is fetched only when the viewer asks to see or copy it (audited).

// Plain builders the dialog is made of (no state of its own).
function dbmT(s) { return window.t ? window.t(s) : s; }
function dbmNode(tag, cls, text) {
  var e = document.createElement(tag);
  if (cls) e.className = cls;
  if (text != null) e.textContent = text;
  return e;
}
function dbmRaw(e) { e.setAttribute('data-no-i18n', ''); return e; }
function dbmButton(text, cls, action, args) {
  var b = dbmNode('button', 'btn btn-sm ' + cls, text);
  b.type = 'button';
  b.setAttribute('data-action', action);
  b.setAttribute('data-args', JSON.stringify(args));
  return b;
}
function dbmReadJson(r) {
  return r.json().then(function (d) { return {ok: r.ok, status: r.status, d: d || {}}; },
                      function () { return {ok: false, status: r.status, d: {message: dbmT('The server sent an unexpected response.')}}; });
}
function dbmFailText(res) { return '✗ ' + ((res.d && (res.d.message || res.d.error)) || dbmT('Failed')); }
function dbmSizeText(b) {
  if (typeof b !== 'number') return '';
  if (b < 1024) return b + ' B';
  if (b < 1048576) return '≈ ' + Math.round(b / 1024) + ' KB';
  return '≈ ' + (b / 1048576).toFixed(1) + ' MB';
}
// A checkbox with its label, for one field of the row editor (`mark` names the field it belongs to).
function dbmCheck(text, mark, id, checked) {
  var l = dbmNode('label', 'form-check-label'), b = dbmNode('input', 'form-check-input me-1');
  b.type = 'checkbox';
  b.checked = !!checked;
  b.setAttribute(mark, id);
  l.appendChild(b);
  l.appendChild(document.createTextNode(text));
  return l;
}
// The input of one field of the row editor: a text box (a textarea for a TEXT column), holding the
// value it had, and disabled for a column the editor leaves alone or a value too long to edit here.
function dbmFieldInput(c, cell, id) {
  var input = dbmNode(c.type.indexOf('text') >= 0 ? 'textarea' : 'input', 'form-control form-control-sm font-monospace');
  input.id = id;
  input.setAttribute('data-col', c.name);
  dbmRaw(input);
  if (input.tagName === 'TEXTAREA') input.rows = 2;
  input.value = dbmWas(cell);
  input.setAttribute('data-was', cell && cell.null ? '\u0000NULL' : dbmWas(cell));
  input.disabled = !!(c.binary || c.generated || (cell && (cell.more || cell.nul)));
  return input;
}
// The text a cell had ('' for none, NULL or a new row).
function dbmWas(cell) { return cell && !cell.null && cell.text != null ? cell.text : ''; }
// Whether a new row may leave column `c` out (it has a default, counts itself, or may be NULL).
function dbmHasDefault(c) { return c['default'] != null || c.extra.indexOf('auto_increment') >= 0 || c.nullable; }
// Why a field can't be edited here, or ''.
function dbmFixedWhy(c, cell) {
  if (c.binary) return dbmT('Binary: not editable here.');
  if (cell && cell.nul) return dbmT('It holds a NUL character (shown as ␀): use the SQL box.');
  if (c.generated) return dbmT('Generated by the database.');
  return cell && cell.more ? dbmT('Too long to edit here: use the SQL box.') : '';
}
// The options under one field: Empty (NULL), Leave out (a new row's default), or why it can't be edited.
function dbmFieldOptions(c, cell, isNew, id) {
  var opts = dbmNode('div', 'd-flex flex-wrap gap-3 small'), fixed = c.binary || c.generated, why = dbmFixedWhy(c, cell);
  if (c.nullable && !fixed) opts.appendChild(dbmCheck(dbmT('Empty (NULL)'), 'data-null-for', id, cell && cell.null));
  if (isNew && !fixed && dbmHasDefault(c)) opts.appendChild(dbmCheck(dbmT('Leave out (use its default)'), 'data-default-for', id, true));
  if (why) opts.appendChild(dbmNode('span', 'text-secondary', why));
  return opts;
}
function dbmEditorField(c, cell, isNew) {
  var row = dbmNode('div', 'mb-2'), id = 'dbm-f-' + Math.random().toString(36).slice(2);
  var lab = dbmRaw(dbmNode('label', 'form-label small mb-0', c.name + ' '));
  lab.htmlFor = id;
  lab.appendChild(dbmRaw(dbmNode('span', 'text-secondary', c.type)));
  row.appendChild(lab);
  row.appendChild(dbmFieldInput(c, cell, id));
  row.appendChild(dbmFieldOptions(c, cell, isNew, id));
  return row;
}

