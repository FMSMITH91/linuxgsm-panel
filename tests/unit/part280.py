def _status_route280(sid):
    old = _ad280._b64(_json280.dumps(_meta280("localhost/lgsm-addon-b3:%s-0ld" % _OLD280[:12], "2.0.2dev (7da5ac86)")))
    now = _ad280._b64(_json280.dumps(_meta280(_ad280.CATALOG["b3"]["image"], "2.0.2 (7c3bbe8c)")))
    got = []
    for meta in (old, now):
        _p9_restore_all()
        _p9_arm(who="part280")
        _p9_patch_sm("shell_as_game_user", lambda server, user, sh, timeout=30, selfname=None, scope=False,
                     stdin_text=None, m=meta: ("os=24.04\npodman=podman version 5.0\nmeta.b3=%s\nstate.b3=active\n" % m,
                                               "", 0))
        _p9_patch(_ra280, "game_account_write_refusal", lambda *a, **k: None)
        d = _p9_client(P9_ADMIN).get("/api/server/%d/addons" % sid).get_json(silent=True) or {}
        row = next((r for r in d.get("addons") or [] if r.get("id") == "b3"), {})
        got.append((row.get("version"), row.get("version_new"), row.get("update")))
