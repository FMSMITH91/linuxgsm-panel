# The stand-in tools' answer for the RCON value: an invented word, not a credential.
_STAND_IN280 = "x"


def _bash280(sh, home, stdin=""):
    run, bindir, log = os.path.join(home, "..", "run"), os.path.join(_TMP280, "bin"), os.path.join(home, "..", "tools.log")
    os.makedirs(run, exist_ok=True)
    _stand_ins255(bindir)
    bus = _socket280.socket(_socket280.AF_UNIX)
    try:
        if not os.path.exists(os.path.join(run, "bus")):
            bus.bind(os.path.join(run, "bus"))
        sh = sh.replace('"/run/user/$(id -u)"', run).replace("/home/u280", home)
        return _sp280.run(["bash", "-c", sh], input=stdin, capture_output=True, text=True, timeout=60,  # nosec B603 B607
                          check=False, env={"PATH": bindir + ":/usr/bin:/bin", "S255_LOG": log, "S255_STATE": "active",
                                            "S255_NR": "0", "S255_SECRET": _STAND_IN280, "S255_UNIT": "/nonexistent",
                                            "S255_START": "ok", "S255_NOFIELD": ""})
    finally:
        bus.close()


def _install280(name, before=(), files=()):
    """A throwaway home with folders `before` and files `files`, then the IW4MAdmin install: (rc, out, home)."""
    home = os.path.join(_TMP280, name, "home")
    for d in before:
        os.makedirs(os.path.join(home, d), exist_ok=True)
    os.makedirs(home, exist_ok=True)
    for f in files:
        os.makedirs(os.path.dirname(os.path.join(home, f)), exist_ok=True)
        with open(os.path.join(home, f), "w", encoding="utf-8") as fh:
            fh.write("the account's own\n")
    sh = _ad280.install_sh("u280", _ad280.IW4MADMIN, "[Unit]\n", "{}\n", _ad280.iw4madmin_files())
    r = _bash280(sh, home, '{"Servers": []}\n')
    # What Podman makes on its first run as the account: its storage and its cache.
    for d in (".local/share/containers/storage", ".cache/containers"):
        os.makedirs(os.path.join(home, d), exist_ok=True)
    return r.returncode, r.stdout, home


def _made280(home):
    p = os.path.join(home, _ad280.HOME_DIR, _ad280.MADE_FILE)
    return open(p, encoding="utf-8").read().split() if os.path.exists(p) else None


def _left280(home):
    return [d for d in (".config", ".local/share", ".local", ".cache", _ad280.HOME_DIR) if os.path.lexists(os.path.join(home, d))]


def _remove280(home):
    r = _bash280(_ad280.remove_sh("u280", _ad280.IW4MADMIN), home)
    return r.returncode, "others=0" in r.stdout


def _fresh280():
    rc, out, home = _install280("fresh")
